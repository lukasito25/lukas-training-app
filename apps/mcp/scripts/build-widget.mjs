// Builds the LiftWise card app (widget/) into one self-contained HTML string:
// src/widget.generated.ts → WIDGET_HTML. No external requests, so the widget CSP stays empty.
import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const at = (p) => fileURLToPath(new URL(p, import.meta.url));
const js = await build({
  entryPoints: [at("../widget/main.tsx")],
  bundle: true, write: false, minify: true, format: "iife", target: "es2020", legalComments: "none",
  jsx: "automatic", jsxImportSource: "preact",
});
const code = js.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const css = (await readFile(at("../widget/styles.css"), "utf8")).replace(/\s*\n\s*/g, "");
const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>LiftWise</title><style>${css}</style></head><body><div id="app"></div><script>${code}</script></body></html>`;
await writeFile(at("../src/widget.generated.ts"), `// Generated by scripts/build-widget.mjs. Do not edit.\nexport const WIDGET_HTML = ${JSON.stringify(html)};\n`);
console.log(`widget: ${(html.length / 1024).toFixed(1)} KB`);
